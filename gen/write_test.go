func TestWriteUnchangedLeavesTheFileAlone(t *testing.T) {
	dir := t.TempDir()
	w := &Writer{Dir: dir}
	f := File{Path: "p_gen.go", Data: gofile("p", "")}

	if _, err := w.Write(f); err != nil {
		t.Fatal(err)
	}
	name := filepath.Join(dir, "p_gen.go")
	old := time.Date(2020, 3, 1, 12, 0, 0, 0, time.UTC)
	if err := os.Chtimes(name, old, old); err != nil {
		t.Fatal(err)
	}

	got, err := w.Write(f)
	if err != nil {
		t.Fatal(err)
	}
	if got[0].Status != Unchanged {
		t.Errorf("status is %v, want unchanged", got[0].Status)
	}
	if got[0].Changed() {
		t.Error("Changed said yes to an unchanged file")
	}

	// The mtime is the point. A generator that rewrites every file wakes every
	// watcher and rebuilds everything downstream of it.
	info, err := os.Stat(name)
	if err != nil {
		t.Fatal(err)
	}
	if !info.ModTime().Equal(old) {
		t.Errorf("the file was rewritten: mtime moved to %v", info.ModTime())
	}
}

