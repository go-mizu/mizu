func TestFormatErrorNamesTheLine(t *testing.T) {
	src := []byte("package p\n\nfunc F() {\n\tconst = 3\n}\n")
	_, err := Format("p/p_gen.go", src)
	if err == nil {
		t.Fatal("a file with a syntax error formatted without complaint")
	}

	var ferr *FormatError
	if !errors.As(err, &ferr) {
		t.Fatalf("got %T, want *FormatError", err)
	}
	if ferr.Path != "p/p_gen.go" {
		t.Errorf("Path is %q", ferr.Path)
	}
	if string(ferr.Src) != string(src) {
		t.Error("FormatError did not keep the source it was given")
	}
	var list scanner.ErrorList
	if !errors.As(err, &list) {
		t.Error("the scanner's error list did not survive the wrapping")
	}

	msg := err.Error()
	for _, want := range []string{"p/p_gen.go:4:", "4 | \tconst = 3"} {
		if !strings.Contains(msg, want) {
			t.Errorf("error message\n%s\ndoes not mention %q", msg, want)
		}
	}
}

