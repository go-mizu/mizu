func TestFormatErrorCountsTheRest(t *testing.T) {
	pos := func(line int) token.Position { return token.Position{Line: line, Column: 1} }
	err := &FormatError{
		Path: "p/p.go",
		Src:  []byte("package p\n"),
		Err: scanner.ErrorList{
			{Pos: pos(1), Msg: "first"},
			{Pos: pos(2), Msg: "second"},
			{Pos: pos(3), Msg: "third"},
		},
	}
	want := "p/p.go:1:1: first (and 2 more)\n1 | package p"
	if got := err.Error(); got != want {
		t.Errorf("Error() =\n%s\nwant\n%s", got, want)
	}
}

