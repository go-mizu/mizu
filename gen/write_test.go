func TestGenerated(t *testing.T) {
	tests := []struct {
		name string
		in   string
		want bool
	}{
		{"header", "// Code generated by mizu gen orm v1; DO NOT EDIT.\n\npackage p\n", true},
		{"stringer", "// Code generated by \"stringer -type=Pill\"; DO NOT EDIT.\npackage p\n", true},
		{"no semicolon", "// Code generated by hand DO NOT EDIT.\n", true},
		{"after a build constraint", "//go:build linux\n\n// Code generated by mizu gen x v1; DO NOT EDIT.\n\npackage p\n", true},
		{"after a licence block", "/*\n * Copyright the authors.\n */\n\n// Code generated by mizu gen x v1; DO NOT EDIT.\n", true},
		{"sql", "-- Code generated by mizu gen queries v1; DO NOT EDIT.\n\nselect 1;\n", true},
		{"yaml", "# Code generated by mizu gen ci v1; DO NOT EDIT.\n\njobs: {}\n", true},
		{"sql that says so too late", "select 1;\n-- Code generated by mizu gen queries v1; DO NOT EDIT.\n", false},
		{"windows line endings", "// Code generated by mizu gen x v1; DO NOT EDIT.\r\n\r\npackage p\r\n", true},
		{"no trailing newline", "// Code generated by mizu gen x v1; DO NOT EDIT.", true},
		{"indented, so not a directive", "\t// Code generated by mizu gen x v1; DO NOT EDIT.\n", false},
		{"after code", "package p\n\n// Code generated by mizu gen x v1; DO NOT EDIT.\n", false},
		{"hand written", "// Package p does something.\npackage p\n", false},
		{"nothing", "", false},
		{"blank lines only", "\n\n\n", false},
		{"the words on their own", "// DO NOT EDIT.\n", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := Generated([]byte(tt.in)); got != tt.want {
				t.Errorf("Generated(%q) = %v, want %v", tt.in, got, tt.want)
			}
		})
	}
}

