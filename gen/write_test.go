// gofile is a small generated Go file, header and all.
func gofile(pkg, body string) []byte {
	return []byte(Header("test", "1", pkg+"/"+pkg+".go") + "\npackage " + pkg + "\n" + body)
}

func TestHeader(t *testing.T) {
	tests := []struct {
		name                       string
		generator, version, source string
		want                       string
	}{
		{
			name: "everything", generator: "orm", version: "1", source: "model/post.go",
			want: "// Code generated by mizu gen orm v1; DO NOT EDIT.\n// Source: model/post.go\n",
		},
		{
			name: "version already has its v", generator: "orm", version: "v2", source: "",
			want: "// Code generated by mizu gen orm v2; DO NOT EDIT.\n",
		},
		{
			name: "no version", generator: "routes", version: "", source: "",
			want: "// Code generated by mizu gen routes; DO NOT EDIT.\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := Header(tt.generator, tt.version, tt.source)
			if got != tt.want {
				t.Errorf("Header(%q, %q, %q) =\n%s\nwant\n%s", tt.generator, tt.version, tt.source, got, tt.want)
			}
			if !Generated([]byte(got)) {
				t.Error("Generated said no to a header this package wrote")
			}
		})
	}
}

