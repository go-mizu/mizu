func TestWriteCreates(t *testing.T) {
	dir := t.TempDir()
	w := &Writer{Dir: dir}

	got, err := w.Write(File{Path: "model/user_gen.go", Data: gofile("model", "const Table = \"users\"\n")})
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 1 || got[0].Status != Created || got[0].Path != "model/user_gen.go" {
		t.Fatalf("got %+v", got)
	}
	if !got[0].Changed() {
		t.Error("a file that was not there is unchanged")
	}

	name := filepath.Join(dir, "model", "user_gen.go")
	data, err := os.ReadFile(name)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), `const Table = "users"`) {
		t.Errorf("wrote\n%s", data)
	}

	info, err := os.Stat(name)
	if err != nil {
		t.Fatal(err)
	}
	// The temporary file the writer renames into place is created 0600, so
	// this is the assertion that the mode gets fixed up before the rename.
	// Windows has no mode bits to speak of, so it sits this one out.
	if runtime.GOOS != "windows" && info.Mode().Perm() != 0o644 {
		t.Errorf("mode is %v, want -rw-r--r--", info.Mode().Perm())
	}
}

