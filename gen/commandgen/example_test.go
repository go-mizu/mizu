package commandgen_test

import (
	"fmt"
	"log"
	"strings"

	"github.com/go-mizu/mizu/gen"
	"github.com/go-mizu/mizu/gen/commandgen"
)

// Running a generator is three steps: load the packages, generate, put what
// came back on disk. mizu gen does this and nothing else, so a program that
// wants the generator without the command around it does the same three.
func Example() {
	// testdata/app is a module holding one package whose command structs carry
	// the //mizu:command marker.
	pkgs, err := gen.Load(gen.Config{Dir: "testdata"}, "./app")
	if err != nil {
		log.Fatal(err)
	}

	files, err := commandgen.Generate(pkgs...)
	if err != nil {
		log.Fatal(err)
	}

	for _, f := range files {
		fmt.Println(f.Path)
		fmt.Println(head(f.Data, 2))
	}

	// Nothing has touched the disk yet. A writer in check mode says what it
	// would do, which is how mizu gen --check tells a build that the checked in
	// output is still the output.
	w := &gen.Writer{Dir: "testdata", Check: true}
	results, err := w.Write(files...)
	if err != nil {
		log.Fatal(err)
	}
	for _, r := range results {
		fmt.Println(r.Status, r.Path)
	}
	// Output:
	// app/commands_gen.go
	// // Code generated by mizu gen command v1; DO NOT EDIT.
	// // Source: app/commands.go
	// unchanged app/commands_gen.go
}

// Analyze is the reading half on its own, for a caller that wants to know what
// is in a package without writing anything.
func ExampleAnalyze() {
	pkgs, err := gen.Load(gen.Config{Dir: "testdata"}, "./app")
	if err != nil {
		log.Fatal(err)
	}
	targets, errs := gen.Scan(pkgs...)
	if len(errs) > 0 {
		log.Fatal(errs[0])
	}

	plan := commandgen.Analyze(pkgs[0], targets)
	for _, c := range plan.Commands {
		fmt.Printf("%s\t%s\t%d flags\n", c.Name, c.Type, len(c.Flags))
	}
	// Output:
	// users:prune	UsersPrune	4 flags
	// db:wipe	DbWipe	4 flags
	// serve	Serve	9 flags
	// deploy	Deploy	0 flags
}

// head is the first n lines, which is as much of a generated file as an example
// has any business printing.
func head(data []byte, n int) string {
	lines := strings.SplitN(string(data), "\n", n+1)
	return strings.Join(lines[:n], "\n")
}
