func TestPackagesIn(t *testing.T) {
	fsys := fstest.MapFS{
		"go.mod":                  {Data: []byte("module example.com/p\ngo 1.27\n")},
		"doc.go":                  {Data: []byte("// Package p is the root.\npackage p\n")},
		"a.go":                    {Data: []byte("package p\n")},
		"a_test.go":               {Data: []byte("// Package p_test is not a package of its own.\npackage p_test\n")},
		"cmd/hello/main.go":       {Data: []byte("// Command hello says hello.\npackage main\n")},
		"empty/notes.txt":         {Data: []byte("nothing to see\n")},
		"tools/bot/go.mod":        {Data: []byte("module example.com/bot\n")},
		"tools/bot/main.go":       {Data: []byte("// Command bot is a module of its own.\npackage main\n")},
		"tools/bot/run/run.go":    {Data: []byte("package run\n")},
		"testdata/fixture/f.go":   {Data: []byte("package fixture\n")},
		"unparseable/nonsense.go": {Data: []byte("this is not Go at all\n")},
	}

	want := []pkgInfo{
		{Dir: ".", Name: "p", Doc: "Package p is the root."},
		{Dir: "cmd/hello", Name: "main", Doc: "Command hello says hello."},
	}
	got := packagesIn(fsys, nestedModules(fsys))
	if len(got) != len(want) {
		t.Fatalf("packagesIn() = %+v\nwant %+v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("packagesIn()[%d] = %+v, want %+v", i, got[i], want[i])
		}
	}
}

// doc.go is where a package that has a lot to say says it, so it is read first.
func TestPackagesInPrefersDocGo(t *testing.T) {
	fsys := fstest.MapFS{
		"p/a.go":   {Data: []byte("// A comment about the file.\npackage p\n")},
		"p/doc.go": {Data: []byte("// Package p is the one worth reading.\npackage p\n")},
	}
	got := packagesIn(fsys, nil)
	if len(got) != 1 || got[0].Doc != "Package p is the one worth reading." {
		t.Errorf("packagesIn() = %+v", got)
	}
}

