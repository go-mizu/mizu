func TestLayoutTableStopsWhenItHasSaidEnough(t *testing.T) {
	pkgs := make([]pkgInfo, mostRows+2)
	for i := range pkgs {
		pkgs[i] = pkgInfo{Dir: "p" + strconv.Itoa(i), Name: "p"}
	}

	got := layoutTable(pkgs)
	if !strings.Contains(got, "| p0 ") {
		t.Error("the table does not start where it should")
	}
	if strings.Contains(got, "| p"+strconv.Itoa(mostRows)+" ") {
		t.Errorf("the table has more than %d rows:\n%s", mostRows, got)
	}
	if want := "And 2 more packages, left out"; !strings.Contains(got, want) {
		t.Errorf("the table does not say what it left out:\n%s", got)
	}
}

