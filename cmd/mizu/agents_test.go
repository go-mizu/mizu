// generateAgents runs the generator over a directory and gives back what it
// wrote, which is the one file it always produces.
func generateAgents(t *testing.T, dir string) string {
	t.Helper()
	files, err := agents(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 1 || files[0].Path != agentsFile {
		t.Fatalf("the generator wrote %+v, want one %s", files, agentsFile)
	}
	return string(files[0].Data)
}

func TestAgents(t *testing.T) {
	dir := scratch(t, commands)
	got := generateAgents(t, dir)

	for _, want := range []string{
		"<!-- Code generated by mizu gen agents v1; DO NOT EDIT.",
		"# commandtest",
		"Go 1.27, 2 packages, 0 commands.",
		"mizu verify --fix",
		"go test -race ./...",
		"| app       | app     | Package app is a set of commands",
		"| mizu gen command v1 | app/commands_gen.go |",
		keepStart,
		keepEnd,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("the file does not contain %q:\n%s", want, got)
		}
	}
	if lines := strings.Count(got, "\n"); lines > 200 {
		t.Errorf("the file is %d lines, and it is meant to stay under 200", lines)
	}
}

// The file describes the whole module, so it cannot depend on which part of it
// somebody asked to generate.
func TestAgentsIgnoresThePackagesItIsGiven(t *testing.T) {
	dir := scratch(t, commands)

	pkgs, err := load(dir, []string{"./broken"})
	if err != nil {
		t.Fatal(err)
	}
	files, err := agents(dir, pkgs...)
	if err != nil {
		t.Fatal(err)
	}
	if got, want := string(files[0].Data), generateAgents(t, dir); got != want {
		t.Errorf("one package gave a different file:\n%s", got)
	}
}

func TestAgentsKeepsWhatIsInTheKeepBlock(t *testing.T) {
	dir := scratch(t, commands)
	const note = "The broken package is meant to be broken. Do not fix it."

	first := generateAgents(t, dir)
	edited := strings.Replace(first, firstNotes, note, 1)
	if edited == first {
		t.Fatal("the first run did not write the notes this test edits")
	}
	add(t, filepath.Join(dir, agentsFile), edited)

	got := generateAgents(t, dir)
	if !strings.Contains(got, note) {
		t.Errorf("the note did not survive:\n%s", got)
	}
	if strings.Contains(got, firstNotes) {
		t.Error("the note was replaced by the one a new file gets")
	}
}

// Running it twice has to give the same file, or a project is never up to date
// and mizu gen --check fails the moment after mizu gen ran.
