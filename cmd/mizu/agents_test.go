func TestReadModule(t *testing.T) {
	tests := []struct {
		name string
		mod  string
		want moduleFacts
	}{
		{
			name: "the whole of what is read",
			mod:  "module example.com/p\n\ngo 1.27\n\nrequire golang.org/x/text v0.41.0\n",
			want: moduleFacts{Path: "example.com/p", Go: "1.27"},
		},
		{
			name: "a requirement that starts with the word go",
			mod:  "module example.com/p\n\nrequire (\n\tgo.uber.org/zap v1.27.0\n)\n\ngo 1.27\n",
			want: moduleFacts{Path: "example.com/p", Go: "1.27"},
		},
		{
			name: "no go directive, which is a module written before 1.12",
			mod:  "module example.com/p\n",
			want: moduleFacts{Path: "example.com/p"},
		},
		{
			name: "a line with nothing after the keyword",
			mod:  "module\nmodule example.com/p\ngo 1.27\n",
			want: moduleFacts{Path: "example.com/p", Go: "1.27"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := readModule(fstest.MapFS{"go.mod": {Data: []byte(tt.mod)}})
			if err != nil {
				t.Fatal(err)
			}
			if got != tt.want {
				t.Errorf("readModule() = %+v, want %+v", got, tt.want)
			}
		})
	}
}

